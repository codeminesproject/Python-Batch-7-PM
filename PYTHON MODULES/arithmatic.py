
def addition(a,b):
    add = a+b
    print(f"addition of {a} and {b} is {add}")

def subtraction(a,b):
    sub = a-b
    print(f"Subtraction of {a} and {b} is {sub}")

def multiplication(a,b):
    mul = a*b
    print("Multiplication:",mul)

def division(a,b):
    div = a/b
    print("Division:",div)
